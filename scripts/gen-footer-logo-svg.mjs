// Static footer lockup: the finished state of the header logo (drawn a +
// "merged."), without the intro animation or the claim line.
import fs from 'node:fs';
const src = fs.readFileSync('app/brand-logo-svg.ts', 'utf8');
let v = JSON.parse(src.slice(src.indexOf('= ') + 2, src.lastIndexOf(';')));
const cut = (re) => { if (!re.test(v)) throw new Error('missing ' + re); v = v.replace(re, ''); };
cut(/<g id="amg-brand-agents"[\s\S]*?<\/text><\/g>/);
cut(/<animate attributeName="opacity" values="0;0;1;1"[^>]*\/>/);
cut(/<animateTransform[^>]*\/>/);
cut(/<text x="0" y="87"[\s\S]*?<\/text>/);
cut(/@media\(prefers-reduced-motion:reduce\)\{[\s\S]*?\}\s*\}/);
v = v.replace('id="amg-brand-drawn-a" opacity="0"', 'id="amg-brand-drawn-a" opacity="1"')
  .replace('<g id="amg-brand-merged" transform="translate(155 0)">', '<g id="amg-brand-merged">')
  .replace('viewBox="0 0 390 97"', 'viewBox="0 0 390 70"')
  .replaceAll('amerged-brand', 'amerged-footer-brand')
  .replaceAll('amg-brand-', 'amg-foot-');
if (!v.includes('opacity="1"') || v.includes('<animate')) throw new Error('static conversion failed');
fs.writeFileSync('app/footer-logo-svg.ts', `/** Footer lockup: static drawn a + "merged." Generated by scripts/gen-footer-logo-svg.mjs. */\nexport const footerLogoSvg = ${JSON.stringify(v)};\n`);
console.log('ok', v.length);
